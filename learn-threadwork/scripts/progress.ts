// npm run progress: runs every exercise's tests, reads your ticks, prints your checklist and writes PROGRESS.md.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { course, runTests, checklist, root, c, statusOf } from "./course";

console.log(c.dim("Running all exercise tests…"));
const results = runTests();

const md: string[] = [];
const out: string[] = [];
let done = 0, checksDone = 0, checksTotal = 0;
let next: string | null = null;

for (const part of course.parts) {
  const exs = course.exercises.filter(e => e.part === part.id);
  const st = exs.map(e => ({ e, s: statusOf(e, results) }));
  const partDone = st.filter(x => x.s.done).length;
  done += partDone;
  md.push(`## Part ${part.id}: ${part.title} (${partDone}/${exs.length})`, "");
  out.push(c.bold(`Part ${part.id}: ${part.title}`) + c.dim(`  ${partDone}/${exs.length}`));
  for (const sec of part.sections) {
    md.push(`**${part.id}${sec.id} ${sec.title}** · [read](${sec.file})`, "");
    for (const { e, s } of st.filter(x => x.e.section === sec.id)) {
      if (!s.done && !next) next = e.id;
      const tag = e.manual ? "tick it in the section" : `${s.passed}/${s.total} tests`;
      md.push(`- [${s.done ? "x" : " "}] **${e.id}** ${e.title} (${tag})`);
      out.push(`  ${s.done ? c.green("✔") : s.passed ? c.yellow("◐") : c.red("○")} ${e.id.padEnd(4)} ${e.title.padEnd(50)} ${c.dim(tag)}`);
    }
    md.push("");
  }
  const checks = checklist(`curriculum/${part.folder}/README.md`, "Knowledge check");
  checksTotal += checks.length; checksDone += checks.filter(x => x.done).length;
  if (checks.length) {
    md.push(`Knowledge check (${checks.filter(x => x.done).length}/${checks.length}):`);
    for (const k of checks) md.push(`- [${k.done ? "x" : " "}] ${k.text}`);
    md.push("");
    out.push(c.dim(`  knowledge check ${checks.filter(x => x.done).length}/${checks.length}`));
  }
}

const total = course.exercises.length;
const pct = Math.round((done / total) * 100);
writeFileSync(path.join(root, "PROGRESS.md"), ["# Your progress", "",
  "Generated by `npm run progress`. Don't edit it: tick knowledge checks in each part's README, and exercises without tests in their section.", "",
  `**Exercises:** ${done}/${total} (${pct}%) · **Knowledge checks:** ${checksDone}/${checksTotal}`, "", ...md].join("\n") + "\n");

console.log("\n" + out.join("\n"));
const bar = "█".repeat(Math.round(pct / 5)) + "░".repeat(20 - Math.round(pct / 5));
console.log(`\n${bar} ${pct}%  ${done}/${total} exercises · ${checksDone}/${checksTotal} knowledge checks`);
console.log(next ? `Next: ${c.bold(`npm run ex ${next}`)}` : c.green("Every exercise is done. Threadwork is finished: it's yours."));
console.log(c.dim("Checklist saved to PROGRESS.md"));
