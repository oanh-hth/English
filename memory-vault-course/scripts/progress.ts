// npm run progress: run every test, then rewrite CHECKLIST.md.
// Exercise boxes are ticked by the tests. "Manual" boxes are yours: tick them by hand in CHECKLIST.md and they are kept.
import fs from 'node:fs';
import path from 'node:path';
import { allExercises, phases } from '../course/curriculum';
import { filePassed, root, runAllTests } from './lib';

const checklistPath = path.join(root, 'CHECKLIST.md');
const previous = fs.existsSync(checklistPath) ? fs.readFileSync(checklistPath, 'utf8') : '';
const manualDone = new Set<string>();
for (const m of previous.matchAll(/^- \[x\] .*<!-- m:([^ ]+) -->/gim)) manualDone.add(m[1]);

console.log('Running all tests... (this takes a few seconds)');
const results = runAllTests();

const passed = new Set<string>();
for (const ex of allExercises) if (ex.tests.every((t) => filePassed(results, t))) passed.add(ex.id);

const total = allExercises.length;
const manualTotal = phases.reduce((n, p) => n + p.manual.length, 0);
const manualCount = phases.reduce((n, p) => n + p.manual.filter((m) => manualDone.has(m.id)).length, 0);
const box = (done: boolean) => (done ? '[x]' : '[ ]');

let md = '# Memory Vault course: progress checklist\n\n';
md += `> Generated by \`npm run progress\`. Exercise boxes tick themselves when their tests pass. Tick the "Manual" boxes yourself (change \`[ ]\` to \`[x]\`); they are kept when this file is regenerated.\n\n`;
md += `**Exercises: ${passed.size} / ${total}**  ·  **Manual steps: ${manualCount} / ${manualTotal}**\n`;

for (const phase of phases) {
  const exDone = phase.exercises.filter((e) => passed.has(e.id)).length;
  const maDone = phase.manual.filter((m) => manualDone.has(m.id)).length;
  const complete = exDone === phase.exercises.length && maDone === phase.manual.length;
  md += `\n## ${complete ? '✅ ' : ''}Part ${phase.id}: ${phase.title}  (${exDone}/${phase.exercises.length} exercises)\n`;
  md += `${phase.goal}\n\nMaterial: [${phase.lesson}](${phase.lesson})\n\n`;
  md += '**Manual**\n';
  for (const m of phase.manual) md += `- ${box(manualDone.has(m.id))} ${m.text} <!-- m:${m.id} -->\n`;
  md += '\n**Exercises** (automatic)\n';
  for (const e of phase.exercises) md += `- ${box(passed.has(e.id))} **${e.id} ${e.title}**: ${e.feature} <!-- e:${e.id} -->\n`;
}
fs.writeFileSync(checklistPath, md);

const next = allExercises.find((e) => !passed.has(e.id));
console.log(`\nExercises passed: ${passed.size} / ${total}`);
for (const phase of phases) {
  const n = phase.exercises.filter((e) => passed.has(e.id)).length;
  console.log(`  Part ${phase.id} ${phase.title.padEnd(34)} ${'#'.repeat(n)}${'.'.repeat(phase.exercises.length - n)} ${n}/${phase.exercises.length}`);
}
console.log(next ? `\nNext up: ${next.id} ${next.title}   ->   npm run ex -- ${next.id}` : '\nAll exercises pass. Finish the manual steps in CHECKLIST.md!');
console.log('Checklist written to CHECKLIST.md');
