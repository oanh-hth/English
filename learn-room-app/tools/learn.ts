/**
 * The course runner. Usage: npm run learn [-- <command>]
 *
 *   status            progress by part (default)
 *   next              the next exercise and how to start it
 *   check [id|part]   run the tests of one exercise (e.g. 1.2), a whole part (e.g. 2), or the next unfinished exercise
 *   hint <id>         reveal the next hint of an exercise
 *   tick <id>         tick / untick a knowledge check (e.g. 1.m2)
 *   reset <id> --yes  restore the starting file(s) of an exercise (your code in them is lost)
 *   sync              rewrite CHECKLIST.md from progress.json
 *   verify            maintainers: check solutions pass, stubs fail, types compile
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { generateStubs } from './make-stubs';

const ROOT = new URL('..', import.meta.url).pathname;

interface Exercise {
  id: string;
  title: string;
  practice: string;
  tests: string[];
  files: string[];
  goal: string;
  hints: string[];
  passesOnStubs?: boolean;
}
interface Part {
  id: number;
  title: string;
  theory: string;
  goal: string;
  milestone: { text: string; run: string };
  exercises: Exercise[];
  manual: { id: string; text: string }[];
}
interface Curriculum {
  title: string;
  parts: Part[];
}
interface Progress {
  done: Record<string, string>;
  ticks: Record<string, boolean>;
  hints: Record<string, number>;
}

const curriculum: Curriculum = JSON.parse(readFileSync(join(ROOT, 'curriculum.json'), 'utf8'));
const allExercises = curriculum.parts.flatMap((p) => p.exercises);
const PROGRESS = join(ROOT, 'progress.json');

const c = {
  bold: (s: string) => `\x1b[1m${s}\x1b[0m`,
  dim: (s: string) => `\x1b[2m${s}\x1b[0m`,
  green: (s: string) => `\x1b[32m${s}\x1b[0m`,
  red: (s: string) => `\x1b[31m${s}\x1b[0m`,
  yellow: (s: string) => `\x1b[33m${s}\x1b[0m`,
  cyan: (s: string) => `\x1b[36m${s}\x1b[0m`,
};

function loadProgress(): Progress {
  if (!existsSync(PROGRESS)) return { done: {}, ticks: {}, hints: {} };
  const raw = JSON.parse(readFileSync(PROGRESS, 'utf8')) as Partial<Progress>;
  return { done: raw.done ?? {}, ticks: raw.ticks ?? {}, hints: raw.hints ?? {} };
}
function saveProgress(p: Progress): void {
  writeFileSync(PROGRESS, JSON.stringify(p, null, 2) + '\n');
  writeFileSync(join(ROOT, 'CHECKLIST.md'), renderChecklist(p));
}

/* ---------- checklist ---------- */
export function renderChecklist(p: Progress): string {
  const total = allExercises.length;
  const done = allExercises.filter((e) => p.done[e.id]).length;
  const manual = curriculum.parts.flatMap((ph) => ph.manual);
  const ticked = manual.filter((m) => p.ticks[m.id]).length;
  const out: string[] = [];
  out.push('# Checklist', '');
  out.push('> Generated by `npm run learn`. Do not edit by hand: run `npm run check` to complete exercises and `npm run learn -- tick <id>` for knowledge checks.', '');
  out.push(`**Exercises:** ${done}/${total}  ·  **Knowledge checks:** ${ticked}/${manual.length}`, '');
  for (const ph of curriculum.parts) {
    const phDone = ph.exercises.filter((e) => p.done[e.id]).length;
    const phTicked = ph.manual.filter((m) => p.ticks[m.id]).length;
    const complete = phDone === ph.exercises.length && phTicked === ph.manual.length;
    out.push(`## ${complete ? '✅ ' : ''}Part ${ph.id}: ${ph.title}`, '');
    out.push(`Read first: [${ph.theory}](${ph.theory})`, '');
    out.push(`**Milestone:** ${ph.milestone.text} Run: \`${ph.milestone.run}\``, '');
    out.push('**Exercises**', '');
    for (const e of ph.exercises) {
      const when = p.done[e.id];
      out.push(`- [${when ? 'x' : ' '}] **${e.id}** ${e.title}${when ? ` _(passed ${when})_` : ''}  `);
      out.push(`  Edit ${e.files.length ? e.files.map((f) => `\`${f}\``).join(', ') : 'nothing'} · tests \`${e.tests.join(', ')}\``);
    }
    out.push('', '**Knowledge checks**', '');
    for (const m of ph.manual) out.push(`- [${p.ticks[m.id] ? 'x' : ' '}] **${m.id}** ${m.text}`);
    out.push('');
  }
  return out.join('\n');
}

/* ---------- running vitest ---------- */
interface TestRun {
  files: Map<string, { passed: number; failed: number; failures: { name: string; message: string }[]; crashed?: string }>;
  ok: boolean;
}

function runVitest(files: string[], env: Record<string, string> = {}): TestRun {
  const dir = mkdtempSync(join(tmpdir(), 'learn-'));
  const outFile = join(dir, 'result.json');
  const bin = join(ROOT, 'node_modules', 'vitest', 'vitest.mjs');
  const res = spawnSync(process.execPath, [bin, 'run', ...files, '--reporter=json', `--outputFile=${outFile}`], {
    cwd: ROOT,
    env: { ...process.env, ...env, FORCE_COLOR: '0' },
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  const run: TestRun = { files: new Map(), ok: false };
  if (!existsSync(outFile)) {
    console.error(c.red('Vitest did not produce a report.'));
    console.error(res.stderr || res.stdout);
    rmSync(dir, { recursive: true, force: true });
    return run;
  }
  const json = JSON.parse(readFileSync(outFile, 'utf8')) as {
    testResults: {
      name: string;
      status: string;
      message?: string;
      assertionResults: { fullName: string; status: string; failureMessages?: string[] }[];
    }[];
  };
  rmSync(dir, { recursive: true, force: true });
  for (const f of json.testResults) {
    const rel = f.name.replace(ROOT, '');
    const entry = { passed: 0, failed: 0, failures: [] as { name: string; message: string }[], crashed: undefined as string | undefined };
    for (const t of f.assertionResults) {
      if (t.status === 'passed') entry.passed++;
      else if (t.status === 'failed') {
        entry.failed++;
        entry.failures.push({ name: t.fullName, message: (t.failureMessages?.[0] ?? '').split('\n')[0] ?? '' });
      }
    }
    if (f.status === 'failed' && entry.failed === 0 && entry.passed === 0) {
      entry.crashed = (f.message ?? 'The test file could not run').split('\n')[0];
    }
    run.files.set(rel, entry);
  }
  run.ok = [...run.files.values()].every((f) => f.failed === 0 && !f.crashed && f.passed > 0);
  return run;
}

function exerciseResult(run: TestRun, e: Exercise) {
  let passed = 0;
  let failed = 0;
  const failures: { name: string; message: string }[] = [];
  let crashed: string | undefined;
  for (const t of e.tests) {
    const f = run.files.get(t);
    if (!f) {
      crashed = `No result for ${t}`;
      continue;
    }
    passed += f.passed;
    failed += f.failed;
    failures.push(...f.failures);
    crashed ??= f.crashed;
  }
  return { passed, failed, failures, crashed, ok: !crashed && failed === 0 && passed > 0 };
}

/* ---------- commands ---------- */
function find(id: string | undefined): Exercise | undefined {
  return allExercises.find((e) => e.id === id);
}
function firstUnfinished(p: Progress): Exercise | undefined {
  return allExercises.find((e) => !p.done[e.id]);
}
function partOf(e: Exercise): Part {
  return curriculum.parts.find((ph) => ph.exercises.includes(e)) as Part;
}
const bar = (n: number, total: number) => {
  const width = 20;
  const filled = total ? Math.round((n / total) * width) : 0;
  return `[${'█'.repeat(filled)}${'░'.repeat(width - filled)}] ${n}/${total}`;
};

function status(p: Progress): void {
  console.log(c.bold(curriculum.title));
  console.log(`\nOverall  ${bar(allExercises.filter((e) => p.done[e.id]).length, allExercises.length)}\n`);
  for (const ph of curriculum.parts) {
    const n = ph.exercises.filter((e) => p.done[e.id]).length;
    const m = ph.manual.filter((x) => p.ticks[x.id]).length;
    console.log(`${c.bold(`Part ${ph.id}`)} ${ph.title}  ${bar(n, ph.exercises.length)}  ${c.dim(`checks ${m}/${ph.manual.length}`)}`);
    for (const e of ph.exercises) console.log(`   ${p.done[e.id] ? c.green('✓') : c.dim('○')} ${e.id} ${e.title}`);
  }
  const next = firstUnfinished(p);
  console.log(next ? `\nNext: ${c.cyan(`${next.id} ${next.title}`)}  (npm run next)` : `\n${c.green('All exercises done!')} Tick the remaining checks with: npm run learn -- tick <id>`);
}

function showExercise(e: Exercise, p: Progress): void {
  const ph = partOf(e);
  if (ph.exercises[0] === e) console.log(c.bold(`\nPart ${ph.id}: ${ph.title}`) + `\n${ph.goal}\nRead ${c.cyan(ph.theory)} first.`);
  console.log(c.bold(`\nExercise ${e.id}: ${e.title}`) + c.dim(`   (Part ${ph.id}: ${ph.title})`));
  console.log(`\n${e.goal}\n`);
  console.log(`Practice  ${e.practice}`);
  console.log(`Theory    ${ph.theory}`);
  console.log(`Edit      ${e.files.length ? e.files.join(', ') : '(nothing)'}`);
  console.log(`Tests     ${e.tests.join(', ')}`);
  console.log(`\nRun       ${c.cyan(`npm run check ${e.id}`)}`);
  console.log(`Stuck?    npm run learn -- hint ${e.id}  ${c.dim(`(${p.hints[e.id] ?? 0}/${e.hints.length} hints used)`)}`);
}

function printResult(e: Exercise, r: ReturnType<typeof exerciseResult>): void {
  const head = `${e.id} ${e.title}`;
  if (r.ok) {
    console.log(`${c.green('✓')} ${head}  ${c.dim(`${r.passed} tests passed`)}`);
    return;
  }
  console.log(`${c.red('✗')} ${head}  ${c.dim(`${r.passed} passed, ${r.failed} failed`)}`);
  if (r.crashed) console.log(`    ${c.red(r.crashed)}`);
  for (const f of r.failures.slice(0, 5)) {
    console.log(`    ${c.red('•')} ${f.name}`);
    if (f.message) console.log(`      ${c.dim(f.message.slice(0, 160))}`);
  }
  if (r.failures.length > 5) console.log(`    ${c.dim(`…and ${r.failures.length - 5} more`)}`);
}

function check(p: Progress, arg: string | undefined): number {
  let targets: Exercise[];
  if (!arg) {
    const next = firstUnfinished(p);
    if (!next) {
      console.log(c.green('Every exercise is already done.'));
      return 0;
    }
    targets = [next];
  } else if (find(arg)) {
    targets = [find(arg) as Exercise];
  } else if (/^\d+$/.test(arg) && curriculum.parts.some((ph) => ph.id === Number(arg))) {
    targets = (curriculum.parts.find((ph) => ph.id === Number(arg)) as Part).exercises;
  } else {
    console.error(`Unknown exercise or part: ${arg}`);
    return 2;
  }
  const run = runVitest([...new Set(targets.flatMap((t) => t.tests))]);
  let failed = 0;
  for (const e of targets) {
    const r = exerciseResult(run, e);
    printResult(e, r);
    if (r.ok) p.done[e.id] ??= new Date().toISOString().slice(0, 10);
    else {
      delete p.done[e.id];
      failed++;
    }
  }
  saveProgress(p);
  if (failed === 0) {
    for (const part of curriculum.parts) {
      const justFinished = part.exercises.every((e) => p.done[e.id]) && part.exercises.some((e) => targets.includes(e));
      if (justFinished) console.log(`\n${c.green(`Part ${part.id} complete!`)} ${part.milestone.text}\n  Try it:  ${c.cyan(part.milestone.run)}\n  Then tick the checks for this part: npm run learn -- status`);
    }
    const next = firstUnfinished(p);
    console.log(next ? `\n${c.green('Nice!')} Next up: ${c.cyan(`${next.id} ${next.title}`)}  (npm run next)` : `\n${c.green('Course complete!')} Now tick your knowledge checks (npm run learn -- status).`);
  } else {
    console.log(`\nRead the first failing test, fix one thing, run ${c.cyan('npm run check')} again.`);
  }
  return failed === 0 ? 0 : 1;
}

function verify(): number {
  let problems = 0;
  const fail = (msg: string) => {
    problems++;
    console.log(`${c.red('✗')} ${msg}`);
  };
  const stubDir = join(ROOT, '.verify');
  rmSync(stubDir, { recursive: true, force: true });
  generateStubs({ force: true, outDir: join(stubDir, 'src') });
  const files = [...new Set(allExercises.flatMap((e) => e.tests))];

  console.log(c.bold('1. Reference solutions must pass every exercise'));
  const sol = runVitest(files, { LEARN_TARGET: 'solutions' });
  for (const e of allExercises) {
    const r = exerciseResult(sol, e);
    if (!r.ok) fail(`${e.id} fails on the solutions (${r.failed} failed, ${r.passed} passed) ${r.crashed ?? ''}`);
  }
  if (!problems) console.log(`${c.green('✓')} all ${allExercises.length} exercises pass on the solutions`);

  console.log(c.bold('\n2. Fresh starter files must fail (except exercise 0.1)'));
  const before = problems;
  const stub = runVitest(files, { LEARN_SRC: '.verify/src' });
  for (const e of allExercises) {
    const r = exerciseResult(stub, e);
    if (e.passesOnStubs ? !r.ok : r.ok) fail(`${e.id} ${e.passesOnStubs ? 'should pass' : 'should fail'} on the starter files`);
  }
  if (problems === before) console.log(`${c.green('✓')} every exercise starts red`);
  rmSync(stubDir, { recursive: true, force: true });

  console.log(c.bold('\n3. Types'));
  for (const [label, project] of [['starter files', 'tsconfig.json'], ['solutions', 'tsconfig.solutions.json']] as const) {
    const tsc = spawnSync(process.execPath, [join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc'), '--noEmit', '-p', project], { cwd: ROOT, encoding: 'utf8' });
    if (tsc.status === 0) console.log(`${c.green('✓')} ${label} type-check`);
    else fail(`${label} do not type-check:\n${(tsc.stdout || tsc.stderr).split('\n').slice(0, 15).join('\n')}`);
  }

  console.log(problems ? c.red(`\n${problems} problem(s)`) : c.green('\nCourse verified.'));
  return problems ? 1 : 0;
}

function main(): number {
  const [cmd = 'status', arg, flag] = process.argv.slice(2);
  const p = loadProgress();
  switch (cmd) {
    case 'status':
      status(p);
      saveProgress(p);
      return 0;
    case 'next': {
      const next = firstUnfinished(p);
      if (!next) {
        console.log(c.green('Every exercise is done. Well done!'));
        return 0;
      }
      showExercise(next, p);
      return 0;
    }
    case 'show': {
      const e = find(arg);
      if (!e) return (console.error('Usage: show <id>'), 2);
      showExercise(e, p);
      return 0;
    }
    case 'check':
      return check(p, arg);
    case 'hint': {
      const e = find(arg);
      if (!e) return (console.error('Usage: hint <id>, for example: npm run learn -- hint 1.2'), 2);
      const used = p.hints[e.id] ?? 0;
      if (used >= e.hints.length) {
        console.log('No more hints. The TODO comments in your file and the tests are your best friends. The solution lives in solutions/ if you must.');
        return 0;
      }
      console.log(`${c.yellow(`Hint ${used + 1}/${e.hints.length}`)}  ${e.hints[used]}`);
      p.hints[e.id] = used + 1;
      saveProgress(p);
      return 0;
    }
    case 'tick': {
      const all = curriculum.parts.flatMap((ph) => ph.manual);
      const m = all.find((x) => x.id === arg);
      if (!m) return (console.error(`Unknown check. Choose one of: ${all.map((x) => x.id).join(', ')}`), 2);
      p.ticks[m.id] = !p.ticks[m.id];
      saveProgress(p);
      console.log(`${p.ticks[m.id] ? c.green('☑') : '☐'} ${m.text}`);
      return 0;
    }
    case 'reset': {
      const e = find(arg);
      if (!e) return (console.error('Usage: reset <id> --yes'), 2);
      if (flag !== '--yes') return (console.log(`This restores ${e.files.join(', ')} to the starting version and loses your code in it. Run again with --yes to confirm.`), 1);
      const written = generateStubs({ force: true, only: e.files.map((f) => f.replace(/^src\//, '')) });
      delete p.done[e.id];
      saveProgress(p);
      console.log(`Restored: ${written.join(', ') || '(nothing)'}`);
      return 0;
    }
    case 'sync':
      saveProgress(p);
      console.log('CHECKLIST.md updated');
      return 0;
    case 'verify':
      return verify();
    default:
      console.error(`Unknown command "${cmd}". See the comment at the top of tools/learn.ts, or the README.`);
      return 2;
  }
}

process.exitCode = main();
