// npm run progress: runs every exercise's tests, reads your ticked knowledge checks,
// prints your checklist and writes it to PROGRESS.md.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { course, runTests, checklist, root, c } from "./course";

console.log(c.dim("Running all exercise tests…"));
const results = runTests();

const lines: string[] = ["# Your progress", "", "Generated by `npm run progress`. Don't edit by hand: tick knowledge checks in each phase README instead.", ""];
let exDone = 0, checksDone = 0, checksTotal = 0;
const rows: string[] = [];
let next: string | null = null;

for (const phase of course.phases) {
  const exercises = course.exercises.filter(e => e.phase === phase.id);
  const checks = checklist(`curriculum/${phase.folder}/README.md`, "Knowledge check");
  const passedHere = exercises.filter(e => { const r = results.get(e.test); return r && r.failed === 0 && r.passed > 0; }).length;
  exDone += passedHere; checksTotal += checks.length; checksDone += checks.filter(x => x.done).length;
  lines.push(`## Phase ${phase.id}: ${phase.title} (${passedHere}/${exercises.length})`, "");
  rows.push(c.bold(`Phase ${phase.id}: ${phase.title}`) + c.dim(`  ${passedHere}/${exercises.length} exercises`));
  for (const e of exercises) {
    const r = results.get(e.test) ?? { passed: 0, failed: 1 };
    const total = r.passed + r.failed, done = r.failed === 0 && r.passed > 0;
    if (!done && !next) next = e.id;
    lines.push(`- [${done ? "x" : " "}] **${e.id}** ${e.title} (${r.passed}/${total} tests) · [lesson](${e.lesson})`);
    rows.push(`  ${done ? c.green("✔") : r.passed ? c.yellow("◐") : c.red("○")} ${e.id.padEnd(4)} ${e.title.padEnd(48)} ${c.dim(`${r.passed}/${total}`)}`);
  }
  if (checks.length) {
    lines.push("", `Knowledge check (${checks.filter(x => x.done).length}/${checks.length}):`);
    for (const k of checks) lines.push(`- [${k.done ? "x" : " "}] ${k.text}`);
    rows.push(c.dim(`  knowledge check ${checks.filter(x => x.done).length}/${checks.length}`));
  }
  lines.push("");
}

const capstone = checklist("curriculum/capstone.md");
lines.push(`## Capstone (${capstone.filter(x => x.done).length}/${capstone.length})`, "");
for (const k of capstone) lines.push(`- [${k.done ? "x" : " "}] ${k.text}`);
const total = course.exercises.length;
lines.splice(4, 0, `**Exercises:** ${exDone}/${total} · **Knowledge checks:** ${checksDone}/${checksTotal} · **Capstone:** ${capstone.filter(x => x.done).length}/${capstone.length}`, "");
writeFileSync(path.join(root, "PROGRESS.md"), lines.join("\n") + "\n");

console.log("\n" + rows.join("\n"));
const pct = Math.round((exDone / total) * 100);
const bar = "█".repeat(Math.round(pct / 5)) + "░".repeat(20 - Math.round(pct / 5));
console.log(`\n${bar} ${pct}%  ${exDone}/${total} exercises · ${checksDone}/${checksTotal} knowledge checks · capstone ${capstone.filter(x => x.done).length}/${capstone.length}`);
console.log(next ? `Next: ${c.bold(`npm run ex ${next}`)}` : c.green("All exercises pass. Time for the capstone."));
console.log(c.dim("Checklist saved to PROGRESS.md"));
